// postgresV117GUIBanner is the fixed header emitted by
// scripts/prepare-postgresql-migration.sh. The GUI artifact may differ from the
// canonical migration only by this banner and by the exact role substitution.
const postgresV117GUIBanner = `-- GENERATED FILE - do not edit and do not commit.
-- Source: postgresql-migration-v1.17.pgsql
-- Generated by scripts/prepare-postgresql-migration.sh.
-- The psql role token was replaced with the quoted role "crowler".
-- This file is bound to that role. If your runtime role differs, regenerate it.
-- Do not reuse or hand-edit this file for another role.
-- Execute this whole file on ONE connection, inside its own transaction.
-- Keep every statement and its order; see docs/database-migrations.md.
--
`

// TestPostgresV117GUICrowlerArtifactMatchesCanonical guards the shipped
// no-shell GUI copy of the PostgreSQL v1.17 migration. The copy is an
// executable distribution artifact for installations whose runtime role is
// exactly "crowler"; it must never drift from the canonical migration.
func TestPostgresV117GUICrowlerArtifactMatchesCanonical(t *testing.T) {
	canonicalPath := filepath.Join("db_migrations", "postgresql-migration-v1.17.pgsql")
	artifactPath := filepath.Join("db_migrations", "postgresql-migration-v1.17.gui-crowler.sql")

	canonical, err := os.ReadFile(canonicalPath)
	if err != nil {
		t.Fatalf("read canonical migration: %v", err)
	}
	artifact, err := os.ReadFile(artifactPath)
	if err != nil {
		t.Fatalf("read GUI artifact: %v", err)
	}

	const token = ":CROWLER_DB_USER"
	const role = `"crowler"`
	if got := strings.Count(string(canonical), token); got != 29 {
		t.Fatalf("canonical migration contains %d %s tokens, expected 29; regenerate the GUI artifact after updating the test if this is intentional", got, token)
	}

	want := postgresV117GUIBanner + strings.ReplaceAll(string(canonical), token, role)
	if string(artifact) != want {
		t.Fatalf("GUI artifact %s is stale or was edited by hand: expected the fixed banner followed by the canonical migration with every %s replaced by %s",
			artifactPath, token, role)
	}
	if strings.Contains(string(artifact), token) {
		t.Fatalf("GUI artifact still contains %s", token)
	}
}

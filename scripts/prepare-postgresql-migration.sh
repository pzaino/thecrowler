#!/usr/bin/env bash
# prepare-postgresql-migration.sh
#
# Produce a GUI-executable copy of a CROWler PostgreSQL migration by replacing
# the psql substitution token :CROWLER_DB_USER with a quoted SQL identifier for
# an existing database role.
#
# The shipped migration is written for psql, which substitutes :CROWLER_DB_USER
# from -v. A generic SQL editor cannot do that, and PostgreSQL's server does not
# understand the token. This helper performs exactly one, validated change and
# leaves every other byte untouched, so the result can be pasted into a GUI
# script runner or executed by any client that sends the file as one script.
#
# It refuses untrusted role names: only an unquoted ASCII identifier of at most
# 63 characters (PostgreSQL's NAMEDATALEN-1) is accepted, and the emitted value
# is always double-quoted.
#
# Usage:
#   scripts/prepare-postgresql-migration.sh --role crowler --output /tmp/migration.gui.sql
#   scripts/prepare-postgresql-migration.sh --role crowler \
#       --input pkg/database/db_migrations/postgresql-agent-goal-v1.17.pgsql \
#       --output /tmp/agent-goal.gui.sql
#
# Options:
#   --role NAME    Required. Existing PostgreSQL role; unquoted identifier.
#   --output FILE  Required. Destination file (refused if it exists, unless --force).
#   --input FILE   Optional. Defaults to the base v1.17 migration.
#   --force        Overwrite an existing output file.
#
# Exit codes: 0 success, 2 usage error, 3 validation/verification failure.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEFAULT_INPUT="$ROOT/pkg/database/db_migrations/postgresql-migration-v1.17.pgsql"
TOKEN=':CROWLER_DB_USER'

usage() {
    sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

die() {
    local code="$1"
    shift
    echo "prepare-postgresql-migration: $*" >&2
    exit "$code"
}

role=""
input="$DEFAULT_INPUT"
output=""
force=0

while [ $# -gt 0 ]; do
    case "$1" in
        --role)
            [ $# -ge 2 ] || die 2 "--role requires a value"
            role="$2"
            shift 2
            ;;
        --output)
            [ $# -ge 2 ] || die 2 "--output requires a value"
            output="$2"
            shift 2
            ;;
        --input)
            [ $# -ge 2 ] || die 2 "--input requires a value"
            input="$2"
            shift 2
            ;;
        --force)
            force=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die 2 "unknown argument: $1"
            ;;
    esac
done

[ -n "$role" ] || die 2 "--role is required"
[ -n "$output" ] || die 2 "--output is required"

# Unquoted PostgreSQL identifier, bounded to NAMEDATALEN-1. This deliberately
# excludes quotes, spaces, dots, semicolons, dollar signs and every other
# character that could change the meaning of the generated statement.
if ! [[ "$role" =~ ^[A-Za-z_][A-Za-z0-9_]{0,62}$ ]]; then
    die 3 "refusing role $role: expected an unquoted identifier matching ^[A-Za-z_][A-Za-z0-9_]{0,62}\$"
fi

[ -f "$input" ] || die 3 "input file not found: $input"
[ -r "$input" ] || die 3 "input file is not readable: $input"

input_abs="$(cd "$(dirname "$input")" && pwd)/$(basename "$input")"
output_dir="$(dirname "$output")"
[ -d "$output_dir" ] || die 3 "output directory does not exist: $output_dir"
output_abs="$(cd "$output_dir" && pwd)/$(basename "$output")"

[ "$input_abs" != "$output_abs" ] || die 3 "refusing to overwrite the source migration in place"

if [ -e "$output_abs" ] && [ "$force" -ne 1 ]; then
    die 3 "output already exists: $output_abs (use --force to overwrite)"
fi
if [ -d "$output_abs" ]; then
    die 3 "output is a directory: $output_abs"
fi

occurrences="$(grep -o -- "$TOKEN" "$input" | wc -l | tr -d '[:space:]')"
[ "$occurrences" -gt 0 ] || die 3 "input contains no $TOKEN token: $input"

quoted="\"$role\""
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT
transformed="$tmp_dir/transformed.sql"
replaced="$tmp_dir/replaced.sql"

# The validated role contains no sed metacharacters, so this substitution cannot
# change anything except the token.
sed "s/$TOKEN/$quoted/g" "$input" > "$transformed"

banner_lines=9
{
    echo "-- GENERATED FILE - do not edit and do not commit."
    echo "-- Source: $(basename "$input_abs")"
    echo "-- Generated by scripts/prepare-postgresql-migration.sh."
    echo "-- The psql role token was replaced with the quoted role $quoted."
    echo "-- This file is bound to that role. If your runtime role differs, regenerate it."
    echo "-- Do not reuse or hand-edit this file for another role."
    echo "-- Execute this whole file on ONE connection, inside its own transaction."
    echo "-- Keep every statement and its order; see docs/database-migrations.md."
    echo "--"
    cat "$transformed"
} > "$replaced"

# Verification: no token may survive, and the body must be exactly the source
# with the token replaced (nothing else added, removed or reordered).
if grep -q -- "$TOKEN" "$replaced"; then
    die 3 "verification failed: $TOKEN still present in the generated file"
fi
if ! cmp -s <(sed "s/$TOKEN/$quoted/g" "$input") <(tail -n "+$((banner_lines + 1))" "$replaced"); then
    die 3 "verification failed: generated body differs from the source outside the token"
fi
remaining="$(tail -n "+$((banner_lines + 1))" "$replaced" | grep -c -- "$quoted" || true)"
if [ "$remaining" -ne "$occurrences" ]; then
    die 3 "verification failed: expected $occurrences replacements, found $remaining"
fi

mv "$replaced" "$output_abs"
chmod 0644 "$output_abs"

echo "prepared: $output_abs"
echo "role:      $quoted"
echo "replaced:  $occurrences occurrence(s) of $TOKEN"
